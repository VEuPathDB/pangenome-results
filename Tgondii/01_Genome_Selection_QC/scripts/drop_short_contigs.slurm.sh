#!/bin/bash
#SBATCH --job-name=drop_short_contigs
#SBATCH --cpus-per-task=1
#SBATCH --mem=4G
#SBATCH --time=00:30:00
#SBATCH --output=drop_short_contigs_%j.out
#SBATCH --error=drop_short_contigs_%j.err
#
# Tgondii-only: removes every contig < MIN_LEN from genomes/ and gff_originals/,
# for every genome in genome_order.txt - a blanket length cutoff, not a
# per-contig evidence check.
#
# READ THIS FIRST: contig_size_profile (see README) found a blanket <10kb drop
# removes 2,388 protein_coding genes across the panel - of those, 289 are known
# SRS/ROP/GRA/RON/AP2/MIC virulence-family genes and ~636 look like
# organelle-genome genes; the remainder (~1,463) are ordinary genes with no
# specific justification for dropping other than contig size alone. Decided
# and accepted already - this script does not distinguish gene-bearing contigs
# from gene-free ones, it drops by length only, and it APPLIES the drop, for
# real, in this one run. The only safety net is the automatic backup below
# (untouched copy of every affected genome's FASTA + GFF) - restore from there
# if this turns out to be wrong.
#
# One run does it all: builds the <genome> <contig> drop list (every contig
# < MIN_LEN, read from each genome's own .fai), backs up the affected
# genomes/GFFs, writes the gene-cost summary, then calls the general-purpose
# drop_contigs.py engine with --apply (same engine used for organelle /
# redundant-contig removal) - genomes/ and gff_originals/ are rewritten by
# the time this job finishes. No second command, no separate --apply step.
#
# Submit from the project folder:
#     sbatch 01_Genome_Selection_QC/scripts/drop_short_contigs.slurm.sh
#
# ─── ADAPT: the paths below, the ### ADAPT ### block, and the #SBATCH lines ───
GENOMES="genomes"                 # step-01 assemblies folder
GFF_DIR="gff_originals"           # step-01 annotations folder
ORDER="genome_order.txt"          # step-01 canonical genome list
MIN_LEN=10000                     # contigs strictly shorter than this are dropped
DROP_LIST="01_Genome_Selection_QC/drop_short_contigs.txt"   # auto-generated, overwritten each run
GENE_TABLE="01_Genome_Selection_QC/contig_size_profile/small_contig_genes.tsv"  # from contig_size_profile.slurm.sh - must use the same MIN_LEN
DROPPED_GENES_OUT="01_Genome_Selection_QC/dropped_genes_summary.tsv"
BACKUP_DIR="01_Genome_Selection_QC/backup_before_short_contig_drop"   # untouched copy of every affected genome's FASTA+GFF
# ────────────────────────────────────────────────────────────────────────────

set -eo pipefail

### ADAPT ### — put samtools and python3 on the PATH:
export MAMBA_ROOT_PREFIX="$HOME/hc-storage/micromamba"
export MAMBA_EXE="$HOME/hc-storage/bin/micromamba/micromamba"
eval "$("$MAMBA_EXE" shell hook --shell bash --root-prefix "$MAMBA_ROOT_PREFIX")"
micromamba activate bioinfo
### END ADAPT ###

set -u

PROJECT_DIR="${SLURM_SUBMIT_DIR:-$PWD}"
GENOME_DIR="$PROJECT_DIR/$GENOMES"
GFF_DIR_PATH="$PROJECT_DIR/$GFF_DIR"
ORDER_FILE="$PROJECT_DIR/$ORDER"
LIST_PATH="$PROJECT_DIR/$DROP_LIST"
DROP_SCRIPT="$PROJECT_DIR/01_Genome_Selection_QC/scripts/drop_contigs.py"
BACKUP_PATH="$PROJECT_DIR/$BACKUP_DIR"

[[ -f "$ORDER_FILE" ]]  || { echo "ERROR: genome list not found: $ORDER_FILE" >&2; exit 1; }
[[ -f "$DROP_SCRIPT" ]] || { echo "ERROR: $DROP_SCRIPT not found" >&2; exit 1; }

fasta_for () {  # basename -> path
    for e in fna fasta fa; do
        [[ -f "$GENOME_DIR/$1.$e" ]] && { echo "$GENOME_DIR/$1.$e"; return 0; }
    done
    return 1
}
gff_for () {  # basename -> path
    for e in gff3 gff; do
        [[ -f "$GFF_DIR_PATH/$1.$e" ]] && { echo "$GFF_DIR_PATH/$1.$e"; return 0; }
    done
    return 1
}

mkdir -p "$BACKUP_PATH/genomes" "$BACKUP_PATH/$(basename "$GFF_DIR")"

# 1. build the drop list: every contig < MIN_LEN, for every genome. Also backs up
#    every affected genome's own FASTA + GFF (untouched, cp -n so a backup already
#    there never gets overwritten by a later, already-modified copy) before anything
#    gets a chance to be rewritten - so --apply is always reversible by hand.
echo "# auto-generated by drop_short_contigs.slurm.sh - contigs < ${MIN_LEN}bp" > "$LIST_PATH"
mapfile -t LABELS < <(grep -vE '^[[:space:]]*(#|$)' "$ORDER_FILE" | awk '{print $1}')
for label in "${LABELS[@]}"; do
    fa=$(fasta_for "$label") || { echo "skip $label (no FASTA)"; continue; }
    [[ -f "${fa}.fai" ]] || samtools faidx "$fa"
    n_before=$(wc -l < "${fa}.fai")
    n_dropped=$(awk -v min="$MIN_LEN" '$2 < min' "${fa}.fai" | wc -l)
    echo "$label: $n_dropped / $n_before contig(s) < ${MIN_LEN}bp"
    if [[ "$n_dropped" -gt 0 ]]; then
        awk -v g="$label" -v min="$MIN_LEN" '$2 < min {print g"\t"$1}' "${fa}.fai" >> "$LIST_PATH"
        cp -n "$fa" "$BACKUP_PATH/genomes/" 2>/dev/null || true
        gff=$(gff_for "$label") && cp -n "$gff" "$BACKUP_PATH/$(basename "$GFF_DIR")/" 2>/dev/null || true
    fi
done
echo "Backups (untouched originals) in $BACKUP_PATH/"

n_total=$(grep -vc '^#' "$LIST_PATH")
if [[ "$n_total" -eq 0 ]]; then
    echo "No contigs < ${MIN_LEN}bp in any genome - nothing to drop."
    exit 0
fi
echo
echo "=== $n_total contig(s) across the panel will be dropped ==="

# 2. gene cost of the drop list, before touching anything
GENE_TABLE_PATH="$PROJECT_DIR/$GENE_TABLE"
if [[ -f "$GENE_TABLE_PATH" ]]; then
    echo
    echo "=== Genes on the dropped contigs ==="
    python3 "$PROJECT_DIR/01_Genome_Selection_QC/scripts/summarize_dropped_genes.py" \
        --drop-list "$LIST_PATH" --gene-table "$GENE_TABLE_PATH" \
        --out "$PROJECT_DIR/$DROPPED_GENES_OUT"
else
    echo
    echo "WARNING: $GENE_TABLE_PATH not found - skipping the gene-cost summary." >&2
    echo "  Run contig_size_profile.slurm.sh (MIN_LEN=${MIN_LEN}) first to get it." >&2
fi

# 3. apply, for real, via the shared drop_contigs.py engine. genomes/ and
#    gff_originals/ get rewritten right here - the backups above are the
#    only way back.
echo
echo "=== APPLYING ==="
python3 "$DROP_SCRIPT" "$LIST_PATH" --genomes-dir "$GENOME_DIR" --gff-dir "$PROJECT_DIR/$GFF_DIR" --apply

echo
echo "Done. genomes/ and $GFF_DIR/ rewritten without contigs < ${MIN_LEN}bp."
echo "Untouched originals backed up in $BACKUP_PATH/ if you need to go back."
